/* Math for the K stations: TeX is rendered to HTML (+ MathML for screen readers) by a locally installed KaTeX at generation
   time, so the page ships no math JavaScript at all. Only the KaTeX stylesheet and fonts are needed in the browser; the shell
   loads them lazily (src/station/math.ts) the first time a page or popup containing math opens. */
import katex from 'katex';

const opt = (displayMode: boolean) => ({ displayMode, output: 'htmlAndMathml' as const, throwOnError: true, strict: 'error' as const, trust: false });
/** inline math */
export const m = (tex: string) => katex.renderToString(tex, opt(false));
/* A phone is narrow, so every long display formula also gets a line-broken twin: it is cut before each top-level relation
   (=, ≤, ⟹, …) into an aligned block, and at top-level \quad gaps into separate lines. The browser shows the one-line form
   and swaps in the broken form only when the one-line form does not fit (src/station/math.ts). */
const REL = new Set(['=', '<', '>', '\\le', '\\leq', '\\ge', '\\geq', '\\approx', '\\ne', '\\equiv', '\\Longrightarrow', '\\implies', '\\iff', '\\Rightarrow']);
const SEP = new Set(['\\quad', '\\qquad']);
const tokens = (tex: string) => tex.match(/\\[a-zA-Z]+|\\[^a-zA-Z]|[\s\S]/g) ?? [];
const trim = (x: string) => x.replace(/^(\s|\\[ ,;:!]|,)+|(\s|\\[ ,;:!]|,)+$/g, '');
const OPS = new Set(['+', '-']);
const weight = (tk: string) => (/^\\[a-zA-Z]+$/.test(tk) || /^\s$/.test(tk) || tk === '{' || tk === '}' || tk === '^' || tk === '_' ? 0 : 1);
/** cut one relation segment (its first token is the relation) at the top-level + or − nearest its middle */
function halve(seg: string[]): string {
  let depth = 0, env = 0, best = -1, bestD = Infinity; const total = seg.reduce((a, t) => a + weight(t), 0); let acc = 0;
  seg.forEach((tk, i) => {
    if (tk === '{' || tk === '\\left' || tk === '(' || tk === '[') depth++; else if (tk === '}' || tk === '\\right' || tk === ')' || tk === ']') depth = Math.max(0, depth - 1);
    else if (tk === '\\begin') env++; else if (tk === '\\end') env--;
    if (!depth && !env && OPS.has(tk) && i > 1 && acc > 2 && total - acc > 2 && Math.abs(acc - total / 2) < bestD) { best = i; bestD = Math.abs(acc - total / 2); }
    acc += weight(tk);
  });
  const j = (x: string[]) => trim(x.join(''));
  return best < 0 ? j(seg) : `${j(seg.slice(0, best))}\\\\&\\qquad ${j(seg.slice(best))}`;
}
/** the line-broken form of a display formula, or null when it has nothing to break at; `fine` also halves each long
    right-hand side at a top-level + or − */
export function brk(tex: string, fine = false): string | null {
  const parts: string[][][] = [[[]]]; let depth = 0, env = 0, breaks = 0;
  for (const tk of tokens(tex)) {
    const part = parts[parts.length - 1]!, seg = part[part.length - 1]!;
    if (tk === '{' || tk === '\\left' || tk === '(' || tk === '[') depth++;
    else if (tk === '}' || tk === '\\right' || tk === ')' || tk === ']') depth = Math.max(0, depth - 1);
    else if (tk === '\\begin') env++;
    else if (tk === '\\end') env--;
    if (depth === 0 && env === 0 && SEP.has(tk)) { parts.push([[]]); breaks++; continue; }
    if (depth === 0 && env === 0 && REL.has(tk)) { part.push([tk]); breaks++; continue; }
    seg.push(tk);
  }
  if (!breaks) return null;
  const rows = parts.filter((segs) => segs.some((x) => trim(x.join(''))))
    .map((segs) => (segs.length === 1 ? trim(segs[0]!.join(''))
      : fine // left side on its own row, every relation on its own indented row
        ? `\\begin{aligned}&${trim(segs[0]!.join(''))}${segs.slice(1).map((x) => `\\\\&\\quad ${halve(x)}`).join('')}\\end{aligned}`
        : `\\begin{aligned}${trim(segs[0]!.join(''))}${segs.slice(1).map((x, i) => `${i ? '\\\\' : ''}&${trim(x.join(''))}`).join('')}\\end{aligned}`));
  return rows.length === 1 ? rows[0]! : `\\begin{gathered}${rows.join('\\\\')}\\end{gathered}`;
}
/** display math: the one-line form, plus line-broken twins (coarse, then fine) when there are any */
export const M = (tex: string) => {
  const forms = [tex, brk(tex), brk(tex, true)].filter((x, i, a): x is string => !!x && a.indexOf(x) === i);
  if (forms.length === 1) return `<div class="kx">${katex.renderToString(tex, opt(true))}</div>`;
  return `<div class="kx kx-w">${forms.map((f) => `<div class="kxf">${katex.renderToString(f, opt(true))}</div>`).join('')}</div>`;
};

/** the stylesheet the browser needs: KaTeX's own CSS with only the woff2 fonts (every browser this site supports reads woff2) */
export function katexCss(src: string): string {
  const out = src.replace(/,url\(fonts\/[^)]+\.woff\) format\("woff"\),url\(fonts\/[^)]+\.ttf\) format\("truetype"\)/g, '')
    .replace(/url\(fonts\//g, 'url(../../node_modules/katex/dist/fonts/');
  if (/\.(woff|ttf)\)/.test(out)) throw new Error('katex.css: unexpected font list (KaTeX CSS format changed)');
  return '/* generated by m2/build.ts from katex/dist/katex.min.css (woff2 only); do not edit */\n' + out + '\n';
}
