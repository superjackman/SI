/* R27: the short home page H and the three layers 首页 → 专区 → 细节站.
   H (generated by m2) holds only: one line, 🎬 tour, 🧒 kids route, the six "I want to…" doorways, one share card and a folded
   "how to browse" box. Every numbered stop carries one level strip (layer, ⬆ up one layer, ⬇ drill down); T1 carries the
   principles route map. H is a page but not a numbered stop, so the 27-stop numbering, progress and challenge codes are unchanged. */
import { describe, expect, it, beforeAll } from 'vitest';
import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { shareURL } from '../../src/share/url';
import { nextStop } from '../../src/onboard';
import { pathFor } from '../../src/analytics';
import { markRmap } from '../../src/station/hydrate';
import { buildSeo } from '../../scripts/seo.mjs';

const GEN = join(__dirname, '../../src/legacy/gen');
const J = <T>(p: string) => JSON.parse(readFileSync(join(GEN, p), 'utf8')) as T;
const KB = J<{ TABORDER: string[]; PATH: Record<string, string[]>; TABN: Record<string, { zh: string; en: string }> }>('kb.json');
const st = (S: string, L: string) => J<{ html: string; cls?: string }>(`st/${S}.${L}.json`);
const dom = (h: string) => { const d = document.createElement('div'); d.innerHTML = h; return d; };
const LANGS = ['zh', 'en'] as const;
const DOORS = ['Api', 'Loc', 'Job', 'Skl', 'Bld', 'T1'];

describe('R27 home page H', () => {
  it('is a page (PATH, TABN) but not a numbered stop: still 27 stops, T1 first', () => {
    expect(KB.TABORDER).toHaveLength(27); expect(KB.TABORDER).not.toContain('H'); expect(KB.TABORDER[0]).toBe('T1');
    expect(KB.PATH.H).toEqual(['H']); expect(KB.TABN.H).toEqual({ zh: '首页', en: 'Home' });
    for (const S of KB.TABORDER) expect(KB.PATH[S]![0], S).toBe('H');
  });
  /* R28 (pilot skeleton): three calm blocks — what this is, the six doorways (the main action), "not sure?" (tour + kids'
     route) and one share line. The poster moved to 进度, "how to browse" to ☰ / 🔍 — they are no longer on H */
  for (const L of LANGS) it(`${L}: one line, six doorways, then tour + kids route, one share line — nothing else`, () => {
    const d = dom(st('H', L).html), kids = [...d.children].map((e) => e.className || e.tagName);
    expect(kids).toEqual(['hm', 'm-door hm-door', 'hm-go', 'hm-sh']);
    expect(d.querySelectorAll('h1')).toHaveLength(1);
    expect(d.querySelectorAll('.hm-go [data-tour=start]')).toHaveLength(1);
    const kid = d.querySelector<HTMLElement>('.hm-go [data-route=kid]')!; expect(kid.dataset.go).toBe('T1');
    expect([...d.querySelectorAll<HTMLElement>('.hm-door .dr-m')].map((b) => b.dataset.go)).toEqual(DOORS);
    expect([...d.querySelectorAll<HTMLElement>('[data-hm]')].map((b) => b.dataset.hm)).toEqual(['share']);
    expect(d.querySelector('details')).toBeNull();
    /* no emoji on the chrome-like buttons (doorway pictures are content) */
    for (const b of d.querySelectorAll('.hm-b')) expect(b.textContent, b.textContent!).not.toMatch(/\p{Extended_Pictographic}/u);
    /* short: well under a screenful of text (R27: < 400 / < 1100) */
    expect((d.textContent ?? '').replace(/\s+/g, '').length).toBeLessThan(L === 'zh' ? 260 : 700);
    expect(d.textContent).not.toMatch(/VPN|科学上网|翻墙/i);
  });
  it('the doorways live only on the home page now (moved off T1, not copied)', () => {
    for (const L of LANGS) for (const S of KB.TABORDER) expect(st(S, L).html, S).not.toContain('<!--m2door-->');
  });
});

describe('R27 level strips: 专区 / 细节站, ⬆ up one layer, ⬇ down', () => {
  for (const L of LANGS) it(`${L}: every stop has exactly one strip, pointing up at its PATH parent`, () => {
    for (const S of KB.TABORDER) {
      const h = st(S, L).html; expect(h.match(/<!--m2zone-->/g)?.length, S).toBe(1);
      const z = dom(h).querySelector<HTMLElement>('.m-zone')!, p = KB.PATH[S]!;
      expect(z.classList.contains(p.length === 2 ? 'z2' : 'z3'), S).toBe(true);
      expect(z.querySelector<HTMLElement>('.mz-up')!.dataset.go, S).toBe(p[p.length - 2]);
      for (const b of z.querySelectorAll<HTMLElement>('.mz-dn [data-go]')) { expect(KB.TABORDER, `${S}→${b.dataset.go}`).toContain(b.dataset.go); expect(b.dataset.go).not.toBe(S); }
      for (const b of z.querySelectorAll('button')) expect(b.textContent!.trim().length, S).toBeGreaterThan(1);
    }
  });
  it('the six "I want to…" zones each offer a way down (T1 through its route map)', () => {
    for (const S of DOORS.filter((s) => s !== 'T1')) expect(dom(st(S, 'zh').html).querySelectorAll('.m-zone .mz-dn [data-go]').length, S).toBeGreaterThan(0);
  });
  it('the level strip sits right under the page head, before the first card', () => {
    for (const S of KB.TABORDER) { const h = st(S, 'zh').html; expect(h.indexOf('<!--m2zone-->'), S).toBeLessThan(h.search(/<div class="card[ "]/)); }
  });
});

describe('R27 T1 principles route map', () => {
  for (const L of LANGS) it(`${L}: 16 theory stops in TABORDER order, numbered as in the 27, plus kids / full routes`, () => {
    const m = dom(st('T1', L).html).querySelector<HTMLElement>('.m-rmap')!;
    const ids = [...m.querySelectorAll<HTMLElement>('.rm-s')].map((b) => b.dataset.rm!);
    expect(ids).toHaveLength(16); expect(new Set(ids).size).toBe(16);
    expect([...ids].sort((a, b) => KB.TABORDER.indexOf(a) - KB.TABORDER.indexOf(b))).toEqual(ids);
    for (const b of m.querySelectorAll<HTMLElement>('.rm-s')) expect(b.querySelector('.rm-n')!.textContent).toBe(String(KB.TABORDER.indexOf(b.dataset.rm!) + 1));
    expect(m.querySelector('[data-rmc]')!.textContent).toBe('0/16');
    expect(m.querySelector('[data-route=kid]')).toBeTruthy(); expect(m.querySelector<HTMLElement>('[data-route=all]')!.dataset.go).toBe('T2');
    expect(m.querySelectorAll('.rm-g>li')).toHaveLength(5);
  });
  it('lights visited stops and counts them; follows progress events', () => {
    localStorage.setItem('aiexp.v2.visited', JSON.stringify(['T1', 'T3', 'K2', 'Api']));
    const d = dom(st('T1', 'zh').html), off = markRmap(d);
    expect([...d.querySelectorAll<HTMLElement>('.rm-s.v')].map((b) => b.dataset.rm)).toEqual(['T1', 'T3', 'K2']);
    expect(d.querySelector('[data-rmc]')!.textContent).toBe('3/16');
    localStorage.setItem('aiexp.v2.visited', JSON.stringify(['T1', 'T3', 'K2', 'T7']));
    document.dispatchEvent(new Event('si-progress'));
    expect(d.querySelector('[data-rmc]')!.textContent).toBe('4/16');
    off(); localStorage.clear();
  });
});

describe('R27 routing, sharing, analytics', () => {
  const loc = { origin: 'https://a.b', pathname: '/SI/', search: '?from=x', hash: '#T3' };
  it('the home page shares as the bare URL; every stop keeps its old #id link', () => {
    expect(shareURL(loc, 'zh', { station: 'H' })).toBe('https://a.b/SI/?lang=zh');
    expect(shareURL(loc, 'en', { station: 'T1' })).toBe('https://a.b/SI/?lang=en#T1');
    expect(shareURL(loc, 'zh', { station: 'T4a', node: 'x' })).toBe('https://a.b/SI/?lang=zh#T4a/x');
  });
  it('▶ next from home is stop 1; numbering of the stops is unchanged', () => {
    expect(nextStop('H', 'all', () => false)).toBe('T1');
    expect(nextStop('T1', 'all', () => false)).toBe('U');
    expect(nextStop('K5', 'all', () => false)).toBeNull();
  });
  it('analytics: H is /home', () => { expect(pathFor('zh', 'H')).toBe('/zh/home'); });
});

describe('R27 static pages', () => {
  let F: Map<string, string>;
  beforeAll(() => { F = buildSeo({ web: resolve(process.cwd()) + '/', base: '/SI/', lastmod: () => '2026-10-25' }); }, 60_000);
  it('trails go 首页 › 全部站点 › zone › … (T1 is a real zone now; no page for H)', () => {
    expect(F.has('s/H/index.html')).toBe(false);
    const bc = (f: string) => [...new DOMParser().parseFromString(F.get(f)!, 'text/html').querySelectorAll('.bc a, .bc li')].map((a) => a.textContent!.trim());
    expect(bc('s/T2/index.html').join('|')).toContain(KB.TABN.T1!.zh);
    expect(bc('en/s/Ua/index.html').join('|')).toContain(KB.TABN.U!.en);
    expect(F.get('s/index.html')).toContain('<p class="open"><a href="/SI/">');
    expect(F.get('en/s/index.html')).toContain('<p class="open"><a href="/SI/?lang=en">');
  });
});
