type Roles = Record<string, { zh: string; en: string }>;
let rolesP: Promise<Roles> | null = null;
const loadRoles = () => (rolesP ||= import('../legacy/gen/search.json').then((m) => m.default as Roles, (e: unknown) => { rolesP = null; void recover(e); return {} as Roles; }));
/* role lines that hold math, as pre-rendered KaTeX HTML (generated by m2/build.ts); loaded with the KaTeX css only when needed */
let mathP: Promise<Roles> | null = null;
const loadMathRoles = () => (mathP ||= Promise.all([import('../legacy/gen/search-math.json'), loadMath()]).then(([m]) => m.default as Roles, (e: unknown) => { mathP = null; console.warn('[search math]', e); return {} as Roles; }));
/** ids whose role line holds math (the plain role then carries TeX: a backslash command, ^ or _) */
export const roleHasTex = (s: string) => /\\[a-zA-Z]+|[\^_]\{?/.test(s);
/** parts split by match strength: name (both languages) + id, then the one-line role (both languages) */
function partHits(q: string, roles: Roles | null): [string[], string[]] {
  const a: string[] = [], b: string[] = [];
  for (const [id, c] of Object.entries(KB.C)) {
    if ((c.n.zh + ' ' + c.n.en + ' ' + id).toLowerCase().includes(q)) a.push(id);
    else if (roles?.[id] && (roles[id].zh + ' ' + roles[id].en).toLowerCase().includes(q)) b.push(id);
  }
  return [a, b];
}
/** live searchFind: name (both languages) + id first, then the one-line role (both languages); top 14 */
export function searchFind(q: string, roles: Roles | null): string[] {
  q = q.trim().toLowerCase(); if (!q) return [];
  const [a, b] = partHits(q, roles);
  return a.concat(b).slice(0, 14);
}
/** R11: stations, cards, labs and quizzes (generated search-x.json): [kind s|c|l|q, element id, station, zh, en]; R15: y = the symbol glossary (id = symbol key or '*', no station) */
export type XRow = [string, string, string, string, string];
let xP: Promise<XRow[]> | null = null;
const loadX = () => (xP ||= import('../legacy/gen/search-x.json').then((m) => m.default as XRow[], (e: unknown) => { xP = null; console.warn('[search x]', e); return [] as XRow[]; }));
export type Hit = { p: string } | { x: XRow };
/** one result list over everything: parts by name, then stations / cards / labs / quizzes by title (both languages), then parts by role; top 16 */
export function searchAll(q: string, roles: Roles | null, xs: XRow[] | null): Hit[] {
  q = q.trim().toLowerCase(); if (!q) return [];
  const [a, b] = partHits(q, roles), o: Hit[] = a.map((p) => ({ p }));
  const kr: Record<string, number> = { s: 0, l: 1, c: 2, q: 3, y: 4 };
  const xm = (xs ?? []).filter((r) => (r[3] + ' ' + r[4] + ' ' + r[1]).toLowerCase().includes(q)).sort((r1, r2) => (kr[r1[0]] ?? 9) - (kr[r2[0]] ?? 9));
  for (const x of xm) o.push({ x });
  for (const p of b) o.push({ p });
  return o.slice(0, 16);
}
const X_KIND: Record<string, 'search.k.s' | 'search.k.c' | 'search.k.l' | 'search.k.q' | 'search.k.y'> = { s: 'search.k.s', c: 'search.k.c', l: 'search.k.l', q: 'search.k.q', y: 'search.k.y' };

function Search({ lang }: { lang: Lang }) {
  const t = useT();
  const open = useApp((s) => s.searchOpen);
  const [q, setQ] = useState('');
  const [roles, setRoles] = useState<Roles | null>(null);
  const inp = useRef<HTMLInputElement>(null);
  const [xs, setXs] = useState<XRow[] | null>(null);
  useEffect(() => { if (open) { void loadRoles().then(setRoles); void loadX().then(setXs); setTimeout(() => inp.current?.focus(), 30); } else inp.current?.blur(); }, [open]);
  const hits = useMemo(() => searchAll(q, roles, xs), [q, roles, xs]);
  const res = useMemo(() => hits.flatMap((h) => ('p' in h ? [h.p] : [])), [hits]);
  const [mathRoles, setMathRoles] = useState<Roles | null>(null);
  const needMath = !mathRoles && res.some((id) => roleHasTex(roles?.[id]?.[lang] ?? ''));
  useEffect(() => { if (needMath) void loadMathRoles().then(setMathRoles); }, [needMath]);
  const pick = (id: string) => { useApp.getState().set({ searchOpen: false }); openAnywhere(id); };
  const pickX = (x: XRow) => {
    useApp.getState().set({ searchOpen: false });
    if (x[0] === 'y') void import('../sym/sheet').then((m) => m.openSym(x[1], lang)).catch(() => { /* chunk failure is handled by the recovery hook */ });
    else if (x[0] === 's') go(x[2], 'top'); else jumpTo(x[1], x[2]);
  };
  const pickH = (h: Hit | undefined) => { if (h) { if ('p' in h) pick(h.p); else pickX(h.x); } };
  return (
    <div className="search">
      <input id="search" ref={inp} type="search" placeholder={t('search.placeholder')} autoComplete="off" enterKeyHint="search" aria-label={t('search.parts')}
        value={q} onChange={(e) => setQ(e.target.value)}
        onKeyDown={(e) => { if (e.key === 'Enter') { e.preventDefault(); pickH(hits[0]); } else if (e.key === 'Escape') useApp.getState().set({ searchOpen: false }); }} />
      <div id="searchRes" className={q.trim() ? 'open' : undefined} onClick={(e) => { const o = (e.target as Element).closest<HTMLElement>('[data-open],[data-sx]'); if (o) { e.stopPropagation(); if (o.dataset.open) pick(o.dataset.open); else pickH(hits[Number(o.dataset.sx)]); } }}>
        {q.trim() && !hits.length ? <div style={{ cursor: 'default' }}>{t('search.none')}</div> : null}
        {hits.map((h, i) => { if ('x' in h) { const x = h.x; return (
          <div key={x[0] + x[1]} data-sx={i} data-kind={x[0]} data-id={x[1]} data-st={x[2]} className={i === 0 ? 'on' : ''}>{x[lang === 'en' ? 4 : 3]}<small>{t(X_KIND[x[0]] ?? 'search.k.c')}{x[0] === 's' || x[0] === 'y' ? '' : ' · ' + tabn(x[2], lang)}</small></div>
        ); } const id = h.p, c = KB.C[id]; if (!c) return null; return (
          <div key={id} data-open={id} className={i === 0 ? 'on' : ''}>{c.n[lang]}{mathRoles?.[id] ? <small>{tabn(c.t, lang)} · <span className="sr-math" dangerouslySetInnerHTML={{ __html: mathRoles[id][lang] }} /></small> : <small>{tabn(c.t, lang)} · {roles?.[id]?.[lang] ?? ''}</small>}</div>
        ); })}
      </div>
    </div>
  );
}

export function TopBar() {
  const t = useT();
  const lang = useApp((s) => s.lang), S = useApp((s) => s.station), drawer = useApp((s) => s.drawerOpen), set = useApp((s) => s.set), setLang = useApp((s) => s.setLang);
  const i = TABORDER.indexOf(S), pv = TABORDER[i - 1], nx = TABORDER[i + 1];
  /* phones show a 7-dot window around the current stop (+ the n/22 counter); wider headers show all 22 */
  const w0 = Math.max(0, Math.min(i - 3, TABORDER.length - 7));
  const prog = useRef<HTMLElement>(null);
  useEffect(() => {
    let p = false;
    const upd = () => { p = false; const d = document.documentElement, m = d.scrollHeight - window.innerHeight; if (prog.current) prog.current.style.width = (m > 0 ? Math.min(100, window.pageYOffset / m * 100) : 0) + '%'; };
    const on = () => { if (!p) { p = true; requestAnimationFrame(upd); } };
    addEventListener('scroll', on, { passive: true }); addEventListener('resize', on); document.addEventListener('si-station-ready', on);
    on();
    return () => { removeEventListener('scroll', on); removeEventListener('resize', on); document.removeEventListener('si-station-ready', on); };
  }, []);
  /* R18: a name that does not fit on one line wraps to two at a smaller size (fit), then smaller still (fit2); never '…' */
  const ttl = useRef<HTMLElement>(null), nm = tabn(S, lang);
  useLayoutEffect(() => {
    const b = ttl.current; if (!b) return;
    const fit = () => {
      b.classList.remove('fit', 'fit2');
      if (b.scrollWidth <= b.clientWidth + 1) return;
      b.classList.add('fit');
      if (b.scrollHeight > b.clientHeight + 1) b.classList.add('fit2');
    };
    fit();
    addEventListener('resize', fit); void document.fonts?.ready.then(fit);
    return () => removeEventListener('resize', fit);
  }, [nm]);
  const pvL = pv ? t('nav.prevStop') + tabn(pv, lang) : t('nav.firstStop');
  const nxL = nx ? t('nav.nextStop') + tabn(nx, lang) : t('nav.lastStop');
  const langL = t('lang.switchTo');
  return (
    <div className="topbar" id="topbar">
      <i id="tbProg" ref={prog} aria-hidden="true" />
      <div className="tb-in">
        <button className="icon-btn tb-ic tb-menu" id="mMenu" aria-label={t('nav.menu.open')} title={t('nav.allStops')} aria-controls="mDrawer" aria-expanded={drawer ? 'true' : 'false'}
          onClick={toggleDrawer} {...svgHtml('menu')} />
        <button className="icon-btn tb-ic tb-nv" id="mPrev" disabled={!pv} aria-label={pvL} title={pvL} onClick={() => pv && go(pv)} {...svgHtml('prev')} />
        <div className="tb-where" id="tbWhere" aria-live="polite"><b ref={ttl} title={nm}>{nm}</b><span className="tb-dots" aria-hidden="true">{dotClasses(S).map((c, k) => <i key={k} className={k < w0 || k >= w0 + 7 ? c + ' far' : c} />)}<small>{i + 1}/{TABORDER.length}</small></span></div>
        <button className="icon-btn tb-ic tb-nv" id="mNext" disabled={!nx} aria-label={nxL} title={nxL} onClick={() => nx && go(nx)} {...svgHtml('next')} />
        <button className="icon-btn tb-ic" id="mSearch" aria-label={t('search.parts')} title={t('search.parts')} aria-controls="search"
          onClick={() => { const o = useApp.getState().searchOpen; set({ searchOpen: !o, sheetOpen: false, popup: null, cardStack: [], full: null }); }} {...svgHtml('search')} />
        <button className="icon-btn tb-ic tb-sh" id="mShare" aria-label={t('share.title')} title={t('share.title')} aria-haspopup="dialog" onClick={openShare} {...svgHtml('share')} />
        <button className="icon-btn tb-ic tb-lang" id="mLang" aria-label={langL} title={langL} lang={lang === 'en' ? 'zh-CN' : 'en'} onClick={() => setLang(lang === 'en' ? 'zh' : 'en')}>{lang === 'en' ? '中' : 'EN'}</button>
        <Search lang={lang} />
      </div>
    </div>
  );
}
